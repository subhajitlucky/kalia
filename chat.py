"""KALIA-Chat v0 — a small, honest REPL for the from-scratch instruction adapter.

This is not a general assistant. It loads frozen KALIA v0.3.1 plus a LoRA
adapter trained on synthetic arithmetic, word, context-QA, instruction,
greeting, refusal and 2-turn dialogue data generated by this repository.

Usage:
    python chat.py --adapter out/chat-v0/chat_lora.pt
    python chat.py --adapter ... --temperature 0      # greedy
    python chat.py --adapter ... --device cpu

The base checkpoint is downloaded from `kalia-lm/kalia-v031` unless
`--base-ckpt` points at a local `.pt` saved by the training code.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from chat_data import NEWLINE_ID, EOS_ID, normalize  # noqa: E402


def load_base(base_ckpt: str | None, device):
    from model import GPT, GPTConfig

    if base_ckpt:
        payload = torch.load(base_ckpt, map_location="cpu", weights_only=False)
        cfg = payload["config"]["model"]
        model = GPT(GPTConfig(**cfg))
        load = model.load_state_dict(payload["model"], strict=False)
        assert not load.missing_keys and not load.unexpected_keys, load
        return model.to(device)

    from huggingface_hub import hf_hub_download
    from safetensors.torch import load_file

    base_dir = Path("/tmp/kalia-chat-base")
    base_dir.mkdir(parents=True, exist_ok=True)
    sf = hf_hub_download("kalia-lm/kalia-v031", "model.safetensors",
                         local_dir=str(base_dir))
    cf = hf_hub_download("kalia-lm/kalia-v031", "config.json",
                         local_dir=str(base_dir))
    raw = json.loads(Path(cf).read_text())
    cfg = {k: v for k, v in raw.items() if k in GPTConfig.__dataclass_fields__}
    model = GPT(GPTConfig(**cfg))
    load = model.load_state_dict(load_file(sf), strict=False)
    assert not load.missing_keys and not load.unexpected_keys, load
    return model.to(device)


def load_adapter(model, path: Path, device):
    from edit_compiler import apply_lora

    payload = torch.load(path, map_location="cpu", weights_only=False)
    rank = int(payload.get("rank", 32))
    alpha = int(payload.get("alpha", 32))
    apply_lora(model, rank, alpha)
    model.to(device)
    load = model.load_state_dict(payload["lora"], strict=False)
    assert not load.unexpected_keys, load.unexpected_keys
    return model, payload


def build_prompt(history: list[tuple[str, str]], user: str) -> str:
    parts = [f"User: {u}\nAssistant: {a}\n" for u, a in history]
    parts.append(f"User: {user}\nAssistant: ")
    return "".join(parts)


@torch.no_grad()
def respond(model, enc, prompt: str, device, max_new: int = 40,
            temperature: float = 0.7, top_k: int = 40) -> str:
    model.eval()
    ids = enc.encode_ordinary(prompt)
    # keep the most recent context if the history is long
    if len(ids) > model.cfg.context_len - max_new - 8:
        ids = ids[-(model.cfg.context_len - max_new - 8):]
    idx = torch.tensor([ids], dtype=torch.long, device=device)
    out: list[int] = []
    for _ in range(max_new):
        logits, _ = model(idx[:, -model.cfg.context_len:])
        logits = logits[:, -1, :]
        if temperature <= 0:
            nxt = logits.argmax(dim=-1, keepdim=True)
        else:
            logits = logits / max(temperature, 1e-6)
            if top_k:
                top = torch.topk(logits, min(top_k, logits.size(-1))).values[:, [-1]]
                logits = logits.masked_fill(logits < top, float("-inf"))
            probs = torch.softmax(logits, dim=-1)
            nxt = torch.multinomial(probs, num_samples=1)
        tok = int(nxt.item())
        if tok in (NEWLINE_ID, EOS_ID):
            break
        out.append(tok)
        idx = torch.cat([idx, nxt], dim=1)
    text = normalize(enc.decode(out))
    if "User:" in text:
        text = text.split("User:")[0].strip()
    return text


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adapter", type=Path, required=True,
                        help="path to chat_lora.pt from the X56 run")
    parser.add_argument("--base-ckpt", type=str, default=None,
                        help="optional local base checkpoint .pt")
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--temperature", type=float, default=0.7)
    parser.add_argument("--top-k", type=int, default=40)
    parser.add_argument("--max-new", type=int, default=40)
    args = parser.parse_args()

    if not args.adapter.exists():
        raise SystemExit(f"adapter not found: {args.adapter}")
    device = torch.device(args.device)
    import tiktoken
    enc = tiktoken.get_encoding("gpt2")

    model = load_base(args.base_ckpt, device)
    model, payload = load_adapter(model, args.adapter, device)
    print("KALIA-Chat v0 — narrow synthetic instruction adapter.")
    print("It can do simple arithmetic, word tasks, short context QA,")
    print("greetings, refusals and 2-turn memory. It is not a general assistant.")
    print("Commands: /clear, /exit")
    print()

    history: list[tuple[str, str]] = []
    while True:
        try:
            user = input("You: ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if not user:
            continue
        if user in ("/exit", "/quit", "exit", "quit"):
            break
        if user in ("/clear", "/reset", "clear", "reset"):
            history.clear()
            print("KALIA: conversation cleared.")
            continue
        prompt = build_prompt(history, user)
        answer = respond(model, enc, prompt, device, max_new=args.max_new,
                         temperature=args.temperature, top_k=args.top_k)
        print(f"KALIA: {answer if answer else '(no response)'}")
        history.append((user, answer))
        # keep the REPL bounded; the model context is 1024 tokens
        while len(history) > 8:
            history.pop(0)


if __name__ == "__main__":
    main()
