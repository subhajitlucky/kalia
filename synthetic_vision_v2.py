"""Synthetic 64x64 three-object shapes dataset for KALIA-Vision v3.

Four shapes, six colors, left/center/right. Fully generated by our own code;
no external images.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

SHAPES = ("circle", "square", "triangle", "star")
COLORS = {
    "red": (220, 40, 40),
    "green": (40, 180, 60),
    "blue": (40, 80, 220),
    "yellow": (240, 200, 40),
    "purple": (160, 60, 200),
    "orange": (240, 130, 40),
}
POSITIONS = {"left": 14, "center": 32, "right": 50}
TEMPLATE = ("a {c1} {s1} on the left, a {c2} {s2} in the center, "
            "and a {c3} {s3} on the right")
SS = 4
SIZE = 64
COLOR_NAMES = tuple(COLORS)


def _draw_shape(draw: ImageDraw.ImageDraw, shape: str, color, cx: int,
                cy: int, r: int) -> None:
    if shape == "circle":
        draw.ellipse((cx - r, cy - r, cx + r, cy + r), fill=color)
    elif shape == "square":
        draw.rectangle((cx - r, cy - r, cx + r, cy + r), fill=color)
    elif shape == "triangle":
        draw.polygon([(cx, cy - r), (cx - r, cy + r), (cx + r, cy + r)],
                     fill=color)
    else:  # star
        pts = []
        for i in range(10):
            ang = -math.pi / 2 + i * math.pi / 5
            rad = r if i % 2 == 0 else r * 0.45
            pts.append((cx + rad * math.cos(ang), cy + rad * math.sin(ang)))
        draw.polygon(pts, fill=color)


def _draw(rng: random.Random, combo: tuple[int, ...]) -> tuple[np.ndarray, str]:
    s1, c1, s2, c2, s3, c3 = combo
    img = Image.new("RGB", (SIZE * SS, SIZE * SS), (238, 238, 238))
    draw = ImageDraw.Draw(img)
    for shape, color, pos in ((SHAPES[s1], COLOR_NAMES[c1], "left"),
                              (SHAPES[s2], COLOR_NAMES[c2], "center"),
                              (SHAPES[s3], COLOR_NAMES[c3], "right")):
        cx = POSITIONS[pos] * SS + rng.randint(-1 * SS, 1 * SS)
        cy = 32 * SS + rng.randint(-2 * SS, 2 * SS)
        r = rng.randint(4, 6) * SS
        _draw_shape(draw, shape, COLORS[color], cx, cy, r)
    img = img.resize((SIZE, SIZE), Image.LANCZOS)
    arr = np.asarray(img, dtype=np.uint8)
    noise = np.random.default_rng(rng.randrange(1 << 30)).integers(
        -4, 5, size=arr.shape, dtype=np.int16
    )
    arr = np.clip(arr.astype(np.int16) + noise, 0, 255).astype(np.uint8)
    caption = TEMPLATE.format(c1=COLOR_NAMES[c1], s1=SHAPES[s1],
                              c2=COLOR_NAMES[c2], s2=SHAPES[s2],
                              c3=COLOR_NAMES[c3], s3=SHAPES[s3])
    return arr, caption


def all_combos() -> list[tuple[int, ...]]:
    return [(s1, c1, s2, c2, s3, c3)
            for s1 in range(len(SHAPES)) for c1 in range(len(COLORS))
            for s2 in range(len(SHAPES)) for c2 in range(len(COLORS))
            for s3 in range(len(SHAPES)) for c3 in range(len(COLORS))]


def split_combos(seed: int = 2026, held_frac: float = 0.2
                 ) -> tuple[list[tuple[int, ...]], list[tuple[int, ...]]]:
    combos = all_combos()
    random.Random(seed).shuffle(combos)
    n_held = int(round(len(combos) * held_frac))
    return combos[n_held:], combos[:n_held]


def parse_combo(caption: str) -> tuple[int, ...]:
    left = caption.split(" on the left")[0]
    center = caption.split(", a ")[1].split(" in the center")[0]
    right = caption.split("and a ")[1].split(" on the right")[0]

    def attrs(t: str):
        s = next(i for i, x in enumerate(SHAPES) if x in t)
        c = next(i for i, x in enumerate(COLOR_NAMES) if x in t)
        return s, c

    l = attrs(left); m = attrs(center); r = attrs(right)
    return (l[0], l[1], m[0], m[1], r[0], r[1])


def render_combo(combo: tuple[int, ...]) -> str:
    s1, c1, s2, c2, s3, c3 = combo
    return TEMPLATE.format(c1=COLOR_NAMES[c1], s1=SHAPES[s1],
                           c2=COLOR_NAMES[c2], s2=SHAPES[s2],
                           c3=COLOR_NAMES[c3], s3=SHAPES[s3])


def generate(n: int, seed: int, combos: list[tuple[int, ...]]
             ) -> tuple[np.ndarray, list[dict]]:
    rng = random.Random(seed)
    images = np.empty((n, SIZE, SIZE, 3), dtype=np.uint8)
    records = []
    for i in range(n):
        combo = rng.choice(combos)
        arr, caption = _draw(rng, combo)
        images[i] = arr
        records.append({"id": i, "caption": caption, "combo": list(combo)})
    return images, records


def audit(images: np.ndarray, records: list[dict]) -> dict:
    counts = {}
    for r in records:
        counts[r["caption"]] = counts.get(r["caption"], 0) + 1
    return {
        "n": len(records),
        "shape": list(images.shape),
        "dtype": str(images.dtype),
        "unique_captions": len(counts),
        "min_caption_count": min(counts.values()),
        "max_caption_count": max(counts.values()),
        "pixel_min": int(images.min()),
        "pixel_max": int(images.max()),
        "pixel_mean": float(images.mean()),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--n-train", type=int, default=1000)
    parser.add_argument("--n-val", type=int, default=100)
    parser.add_argument("--n-test", type=int, default=100)
    parser.add_argument("--seed", type=int, default=2026)
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    seen, held = split_combos(args.seed)
    manifest = {"combos": {"seen": len(seen), "held": len(held)},
                "held": [list(c) for c in held[:50]], "splits": {}}
    for name, n, seed, combos in (("train", args.n_train, 21, seen),
                                  ("val", args.n_val, 22, seen),
                                  ("test", args.n_test, 23, held)):
        images, records = generate(n, seed, combos)
        np.save(args.out_dir / f"{name}_images.npy", images)
        with open(args.out_dir / f"{name}_captions.jsonl", "w") as fh:
            for r in records:
                fh.write(json.dumps(r, sort_keys=True) + "\n")
        manifest["splits"][name] = audit(images, records)
        manifest["splits"][name]["images_sha256"] = hashlib.sha256(
            (args.out_dir / f"{name}_images.npy").read_bytes()
        ).hexdigest()
        print(name, manifest["splits"][name]["n"], flush=True)
    (args.out_dir / "audit.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    )
    print(json.dumps({k: v["n"] for k, v in manifest["splits"].items()}))


if __name__ == "__main__":
    main()
