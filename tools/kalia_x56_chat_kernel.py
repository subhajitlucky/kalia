    for x, y, lm, tm, attn in train_loader:
        x = x.to(device, non_blocking=True)
        y = y.to(device, non_blocking=True)
        lm = lm.to(device, non_blocking=True)
        attn = attn.to(device, non_blocking=True)
        lr_now = lr_at(step, total_steps, LR, WARMUP)
        for group in opt.param_groups:
            group["lr"] = lr_now
        opt.zero_grad(set_to_none=True)
        with torch.autocast(device_type="cuda", dtype=torch.float16,
                            enabled=device.type == "cuda"):
            _, loss = model(x, targets=y, loss_mask=lm, attn_mask=attn)
        scaler.scale(loss).backward()
        scaler.unscale_(opt)
        torch.nn.utils.clip_grad_norm_(
            [p for p in model.parameters() if p.requires_grad], 1.0
        )
        scaler.step(opt)
        scaler.update()
        if step % 50 == 0:
            rec = {"step": step, "loss": float(loss.detach()),
                   "lr": lr_now, "seconds": time.time() - t0}
            history.append(rec)
            print(json.dumps(rec), flush=True)
        step += 1

    model.eval()
    val_metrics, _, _ = eval_records(model, splits["val"], per_task=100)
    print("epoch", epoch, "val", json.dumps(val_metrics, sort_keys=True), flush=True)
    if val_metrics["overall"]["acc"] > best_val:
        best_val = val_metrics["overall"]["acc"]
        best_state = lora_state_dict(model)
        print("new best", best_val, flush=True)
    model.train()

