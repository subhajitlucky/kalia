def sample_subset(records: list[dict], per_task: int, seed: int = 56) -> list[dict]:
    rng = random.Random(seed)
    by: dict[str, list[dict]] = {}
    for r in records:
        by.setdefault(r["task"], []).append(r)
    out = []
    for task in sorted(by):
        rs = by[task][:]
        rng.shuffle(rs)
        out.extend(rs[:per_task])
    return out


@torch.no_grad()
def eval_records(model, records: list[dict], per_task: int = 300):
    subset = sample_subset(records, per_task)
    preds = []
    for r in subset:
        preds.append(chat_data.generate_response(model, r, enc, device, max_new=24))
    by: dict[str, dict[str, float]] = {}
    for r, p in zip(subset, preds):
        task = r["task"]
        d = by.setdefault(task, {"n": 0, "correct": 0, "format": 0})
        d["n"] += 1
        d["correct"] += int(chat_data.check_record(r, p))
        d["format"] += int(chat_data.format_ok(r, p))
    metrics = {}
    for task, d in by.items():
        metrics[task] = {"n": int(d["n"]), "acc": d["correct"] / d["n"],
                         "format": d["format"] / d["n"]}
    n = len(subset)
    metrics["overall"] = {
        "n": n,
        "acc": sum(d["correct"] for d in by.values()) / n,
        "format": sum(d["format"] for d in by.values()) / n,
    }
    return metrics, subset, preds


def lr_at(step: int, total: int, base: float, warmup: int,
          min_ratio: float = 0.1) -> float:
    if step < warmup:
        return base * (step + 1) / warmup
    progress = (step - warmup) / max(1, total - warmup)
    coeff = 0.5 * (1.0 + math.cos(math.pi * min(1.0, progress)))
    return base * (min_ratio + (1 - min_ratio) * coeff)


