#!/usr/bin/env python3
"""Record the live Kaggle asset state into ``kaggle/README.md``.

The 2026-10-17 audit found drift between the kernels that exist on Kaggle and
the metadata files recorded in this directory: ten live kernels had no metadata
file, and three metadata files named kernels that no longer exist. The same audit
confirmed every KALIA kernel and dataset is private; this ledger records *what
exists*, and ``tools/audit_public_state.py`` checks *what is exposed*, so the two
questions cannot blur into each other.

Regenerated from the live account, the same way ``tools/collect_results.py``
keeps ``experiments.json`` honest. It requires the owner's Kaggle CLI auth, so it
is run by hand, never in CI.

Usage:
    python tools/collect_kaggle_state.py          # rewrite kaggle/README.md
    python tools/collect_kaggle_state.py --check  # fail if the ledger is stale
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KAGGLE_DIR = ROOT / "kaggle"
OUT = KAGGLE_DIR / "README.md"


def kaggle_cli() -> str:
    candidate = Path(sys.executable).parent / "kaggle"
    return str(candidate) if candidate.exists() else "kaggle"


def fetch(kind: str) -> list[dict]:
    """List the owner's live assets of one kind. Empty output is an error: it
    means the CLI is not authenticated, not that the account has no assets."""
    cmd = [kaggle_cli(), kind, "list", "-m", "--page-size", "200", "--format", "json"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"kaggle {kind} list failed: {r.stderr[-300:]}")
    rows = json.loads(r.stdout or "[]")
    if not rows:
        raise SystemExit(f"kaggle {kind} list returned nothing -- is the CLI authenticated?")
    return rows


def recorded_ids() -> dict[str, str]:
    out: dict[str, str] = {}
    for f in sorted(KAGGLE_DIR.glob("kernel-metadata*.json")):
        try:
            out[json.loads(f.read_text())["id"]] = f.name
        except (KeyError, json.JSONDecodeError):
            continue
    return out


def _mb(n: int) -> str:
    if n >= 1_000_000_000:
        return f"{n / 1e9:.2f} GB"
    return f"{n / 1e6:.1f} MB"


def render(kernels: list[dict], datasets: list[dict], recorded: dict[str, str]) -> str:
    lines = [
        "# Kaggle assets — live state ledger",
        "",
        "Generated by `python tools/collect_kaggle_state.py` from the live account. Do not",
        "hand-edit; `--check` fails if this file stops matching Kaggle. Every KALIA kernel",
        "and dataset is private; exposure is checked separately by",
        "`tools/audit_public_state.py`.",
        "",
        f"## Kernels ({len(kernels)})",
        "",
        "| ref | title | last run | recorded in repo |",
        "|---|---|---|---|",
    ]
    for k in sorted(kernels, key=lambda k: str(k.get("lastRunTime")), reverse=True):
        ref = k.get("ref", "?")
        rec = f"`{recorded[ref]}`" if ref in recorded else "**no metadata file**"
        lines.append(
            f"| `{ref}` | {k.get('title', '')} | {str(k.get('lastRunTime', ''))[:10]} | {rec} |"
        )
    lines += [
        "",
        f"## Datasets ({len(datasets)})",
        "",
        "| ref | title | size | last updated |",
        "|---|---|---|---|",
    ]
    for d in sorted(datasets, key=lambda d: str(d.get("lastUpdated")), reverse=True):
        lines.append(
            f"| `{d.get('ref', '?')}` | {d.get('title', '')} | {_mb(int(d.get('size') or 0))} "
            f"| {str(d.get('lastUpdated', ''))[:10]} |"
        )
    live = {k.get("ref") for k in kernels}
    stale = sorted(set(recorded) - live)
    lines += ["", "## Repo metadata files without a live kernel", ""]
    if stale:
        for ref in stale:
            lines.append(f"- `{ref}` (`{recorded[ref]}`) — renamed or removed on Kaggle")
    else:
        lines.append("None.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = render(fetch("kernels"), fetch("datasets"), recorded_ids())
    if args.check:
        if not OUT.exists():
            print(f"{OUT} does not exist")
            return 1
        if OUT.read_text() != text:
            print("kaggle/README.md is STALE relative to the live account")
            return 1
        print("kaggle/README.md is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
